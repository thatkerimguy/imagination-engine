// Android Auto Backup / device-transfer rules for Kinetic Writer (DIRECTIVE-02 §C).
// Manuscripts and Master Lock hashes live in one expo-sqlite database
// (`filesDir/SQLite/kinetic-writer.db` + `-wal` / `-shm`); emergency snapshots are zips in
// `filesDir/backups`. None of it may reach Google's cloud backup or a device-to-device copy:
// a live WAL copied mid-write corrupts on restore, and locked manuscripts must stay on the phone.
// `android:allowBackup="false"` (app.json) already blocks cloud backup on every API level; the
// rules below are the second fence and the only one that governs Android 12+ device transfer.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const DB = 'SQLite/kinetic-writer.db';
/** [domain, path] pairs excluded everywhere. */
const EXCLUDES = [
  ['file', 'SQLite'],
  ['file', DB],
  ['file', `${DB}-wal`],
  ['file', `${DB}-shm`],
  ['file', 'backups'],
  ['database', '.'],
  ['sharedpref', '.'],
];

const rules = (indent) =>
  EXCLUDES.map(([d, p]) => `${indent}<exclude domain="${d}" path="${p}" />`).join('\n');

/** Android 12+ (API 31+): `android:dataExtractionRules`. */
const dataExtractionRules = () =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- kn-android-release: generated by plugins/android-backup-rules.js -->',
    '<data-extraction-rules>',
    '    <cloud-backup>',
    rules('        '),
    '    </cloud-backup>',
    '    <device-transfer>',
    rules('        '),
    '    </device-transfer>',
    '</data-extraction-rules>',
    '',
  ].join('\n');

/** Android 11 and lower: `android:fullBackupContent`. */
const fullBackupContent = () =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- kn-android-release: generated by plugins/android-backup-rules.js -->',
    '<full-backup-content>',
    rules('    '),
    '</full-backup-content>',
    '',
  ].join('\n');

const BACKUP_ATTRS = {
  'android:allowBackup': 'false',
  'android:fullBackupContent': '@xml/backup_rules',
  'android:dataExtractionRules': '@xml/data_extraction_rules',
};

function withBackupManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;
    manifest.$['xmlns:tools'] = manifest.$['xmlns:tools'] || 'http://schemas.android.com/tools';
    const app = manifest.application && manifest.application[0];
    if (!app) throw new Error('android-backup-rules: <application> not found');
    Object.assign(app.$, BACKUP_ATTRS);
    // Win over any library manifest that declares its own backup attributes.
    const replace = new Set((app.$['tools:replace'] || '').split(',').filter(Boolean));
    Object.keys(BACKUP_ATTRS).forEach((a) => replace.add(a));
    app.$['tools:replace'] = [...replace].join(',');
    return cfg;
  });
}

function withBackupXml(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'data_extraction_rules.xml'), dataExtractionRules());
      fs.writeFileSync(path.join(dir, 'backup_rules.xml'), fullBackupContent());
      return cfg;
    },
  ]);
}

module.exports = function withBackupRules(config) {
  return withBackupXml(withBackupManifest(config));
};
module.exports.EXCLUDES = EXCLUDES;
module.exports.dataExtractionRules = dataExtractionRules;
module.exports.fullBackupContent = fullBackupContent;
